"""Post-fix API verification against canonical per-image metrics (read-only)."""
from datetime import datetime, timezone
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from src.web.app import app
from src.eval.analyze_task5 import verify_metric_delivery
from src.eval.metric_utils import RESULTS,sha256
from src.eval.task5_runtime import read_csv

OUT=ROOT/'docs/13_11/sau_sua_web_app'


def check(value,message):
    if not value: raise ValueError(message)


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    proof=dict(status='RUNNING',checked_at_utc=datetime.now(timezone.utc).isoformat(),
               scope='real Flask routes; no canonical data regenerated by this script',cases=[])
    try:
        verify_metric_delivery()
        before=json.loads((ROOT/'docs/13_11/kiem_tra_web_app/API_NUMERICAL_AUDIT.json').read_text(encoding='utf-8'))
        protected={name:digest for name,digest in before['input_sha256'].items()
                   if name=='config.yaml' or 'outputs/metrics/' in name.replace('\\','/')}
        changed=[p for p,h in protected.items() if sha256(ROOT/p)!=h]
        check(not changed,f'Canonical config/metric data changed: {changed}')
        proof['canonical_files_unchanged']=len(protected)
        client=app.test_client()
        settings=client.get('/api/settings').get_json()
        threshold=next(pair for s,pair in settings['canny_thresholds'].items() if float(s)==2)
        rows=read_csv(RESULTS/'tier2_results_both.csv')
        index={(r['task'],r['image'],r['sigma']):r for r in rows if r['source']=='python'}
        for category,count,algo,task in [('bsds',10,'canny','edge_bsds'),('drive',10,'frangi','ridge_drive'),('blob',5,'blob','blob_log')]:
            for i in range(1,count+1):
                image=f'{category}_{i:02d}'
                payload=dict(image_id=image,algorithm=algo)
                if algo=='canny': payload.update(sigma=2,p_low=threshold[0],p_high=threshold[1])
                # Other defaults, including dark/bright polarity, come from the
                # app's settings/annotation, not parameters inserted by the test.
                r=client.post('/api/process',json=payload)
                check(r.status_code==200,f'API failed: {image}')
                result=r.get_json()
                expected=index[task,image,'2.0' if algo=='canny' else 'multiscale']
                for key in ('precision','recall','f1'):
                    check(abs(result['gt_metrics'][key]-round(float(expected[key]),4))<1e-12,f'{image}: incorrect {key}')
                proof['cases'].append(dict(image=image,algorithm=algo,precision=result['gt_metrics']['precision'],
                                           recall=result['gt_metrics']['recall'],f1=result['gt_metrics']['f1'],status='PASS'))
                print(f'PASS {image}: F1={result["gt_metrics"]["f1"]:.4f}',flush=True)
        proof['canonical_presets']=dict(passed=len(proof['cases']),total=25)

        def process(**payload):
            response=client.post('/api/process',json=payload)
            check(response.status_code==200,f'Expected success: {payload}')
            return response.get_json()

        canny=process(image_id='bsds_03',algorithm='canny',sigma=2)
        check(canny['fiji_metrics']['has_fiji'] and canny['fiji_metrics']['pearson']>.9999,'Wrong Canny reference')
        check(not any('_edge_' in f for f in canny['fiji_metrics']['files']),'Native Edges used as gradient')
        blob=process(image_id='bsds_01',algorithm='blob')
        check(not blob['fiji_metrics']['has_fiji'] and blob['img_fiji'] is None,'Incomplete blob stack had fake reference')
        angle=process(image_id='bsds_01',algorithm='gradient',display_type='angle',sigma=2)
        check(angle['fiji_metrics']['kind']=='angular' and angle['fiji_metrics']['pearson'] is None,'Incorrect angular metric')
        proof['reproduced_failures_fixed']=dict(canny_reference=canny['fiji_metrics'],
                                                incomplete_blob=blob['fiji_metrics'],gradient_angle=angle['fiji_metrics'])
        r=client.get('/api/benchmarks');check(r.status_code==200,'Benchmark gate not valid')
        benchmark=r.get_json();check(benchmark['provenance']['status']=='VALID','Missing provenance')
        check(benchmark['tier1_counts']['strict']==35 and benchmark['tier1_counts']['strict_failed']==185,'Strict status changed')
        proof['benchmark_provenance']=benchmark['provenance']
        proof['tier1_counts']=benchmark['tier1_counts']
        figures=client.get('/api/figures');check(figures.status_code==200,'Analysis gate not valid')
        check(len(figures.get_json())==10,'Expected 10 figures')
        check(all(client.get(f['url']).status_code==200 for f in figures.get_json()),'Figure route failure')
        proof['figures_verified']=10
        proof['source_sha256']={str(p.relative_to(ROOT)):sha256(p) for p in [*sorted((ROOT/'src/web').glob('*.py')),ROOT/'src/web/templates/index.html',ROOT/'tests/test_web.py']}
        proof['status']='PASS'
    except Exception as exc:
        proof.update(status='FAIL',error=f'{type(exc).__name__}: {exc}')
        raise
    finally:
        (OUT/'API_REGRESSION.json').write_text(json.dumps(proof,ensure_ascii=False,indent=2),encoding='utf-8')
        print(json.dumps({k:v for k,v in proof.items() if k not in ('cases','source_sha256','reproduced_failures_fixed')},ensure_ascii=True,indent=2))


if __name__=='__main__': main()
